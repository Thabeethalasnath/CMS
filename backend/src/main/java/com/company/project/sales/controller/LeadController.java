package com.company.project.sales.controller;

import com.company.project.common.response.ApiResponse;
import com.company.project.common.response.PageResponse;
import com.company.project.sales.dto.*;
import com.company.project.sales.service.LeadService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import org.springframework.data.domain.PageRequest;
import org.springframework.data.domain.Pageable;
import org.springframework.data.domain.Sort;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

@RestController
@RequestMapping("/api/v1/leads")
@RequiredArgsConstructor
@Tag(name = "Leads API", description = "Endpoints for managing sales leads and KPI summaries")
public class LeadController {

    private final LeadService leadService;

    @GetMapping
    @Operation(summary = "Get paginated, filtered, and sorted leads")
    public ResponseEntity<ApiResponse<PageResponse<LeadResponse>>> getLeads(
            @RequestParam(required = false) String search,
            @RequestParam(required = false) String stage,
            @RequestParam(required = false) String status,
            @RequestParam(required = false) String ownerId,
            @RequestParam(required = false) String source,
            @RequestParam(defaultValue = "0") int page,
            @RequestParam(defaultValue = "10") int size,
            @RequestParam(defaultValue = "createdAt") String sortBy,
            @RequestParam(defaultValue = "desc") String sortDir
    ) {
        Sort sort = "asc".equalsIgnoreCase(sortDir) ? Sort.by(sortBy).ascending() : Sort.by(sortBy).descending();
        Pageable pageable = PageRequest.of(page, size, sort);
        PageResponse<LeadResponse> leads = leadService.getLeads(pageable, search, stage, status, ownerId, source);
        return ResponseEntity.ok(ApiResponse.success(leads));
    }

    @GetMapping("/summary")
    @Operation(summary = "Get KPI summary metrics with month-over-month trends for Leads")
    public ResponseEntity<ApiResponse<LeadSummaryDto>> getSummary() {
        LeadSummaryDto summary = leadService.getSummary();
        return ResponseEntity.ok(ApiResponse.success(summary));
    }

    @GetMapping("/{id}")
    @Operation(summary = "Get lead by ID")
    public ResponseEntity<ApiResponse<LeadResponse>> getLeadById(@PathVariable String id) {
        LeadResponse lead = leadService.getLeadById(id);
        return ResponseEntity.ok(ApiResponse.success(lead));
    }

    @PostMapping
    @Operation(summary = "Create a new lead (ID generated by backend)")
    public ResponseEntity<ApiResponse<LeadResponse>> createLead(@Valid @RequestBody CreateLeadRequest request) {
        LeadResponse created = leadService.createLead(request);
        return ResponseEntity.status(HttpStatus.CREATED).body(ApiResponse.success("Lead created successfully", created));
    }

    @PutMapping("/{id}")
    @Operation(summary = "Update an existing lead")
    public ResponseEntity<ApiResponse<LeadResponse>> updateLead(
            @PathVariable String id,
            @Valid @RequestBody UpdateLeadRequest request
    ) {
        LeadResponse updated = leadService.updateLead(id, request);
        return ResponseEntity.ok(ApiResponse.success("Lead updated successfully", updated));
    }

    @DeleteMapping("/{id}")
    @Operation(summary = "Delete a lead (restricted to dev profile or admin)")
    public ResponseEntity<ApiResponse<Void>> deleteLead(@PathVariable String id) {
        leadService.deleteLead(id);
        return ResponseEntity.ok(ApiResponse.success("Lead deleted successfully", null));
    }
}
